#!/usr/bin/env python3
"""Generate platforms/<ecu>/terms.yaml: which canonical-term names each platform's own docs use.

Usage:
  python3 -I platform_terms.py [--collateral collateral/vendor] [--write] [--min-docs 2]

For every vendor folder in PLATFORMS, counts the documents (markdown topics, or PDF pages for
single-file manuals) that contain each name of each term in principles/glossary/terms.yaml.
Short all-caps abbreviations match case-sensitively, everything else case-insensitively, on word
boundaries. Without --write it prints a summary; with --write it (re)writes the generated part of
platforms/<folder>/terms.yaml. Hand-curated entries go in the same file under `overrides:` and are kept.
The output is evidence of usage, not proof of the primary on-screen name: check `top` against the docs.
"""
import argparse, collections, re, sys, time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import miniyaml  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
# vendor collateral folder -> platforms/<folder> (one folder per ECU family; docs may cover several generations)
PLATFORMS = {"link": "link-g4plus", "haltech": "haltech", "motec": "motec", "ecumaster": "ecumaster",
             "maxxecu": "maxxecu", "aem": "aem-infinity", "holley": "holley-efi", "msextra": "megasquirt",
             "speeduino": "speeduino", "fueltech": "fueltech"}

def units(folder):
    """Yield text units: one per markdown topic, or one per '## [p.N]' page for PDF conversions."""
    for p in sorted(folder.rglob("*.md")):
        t = p.read_text(encoding="utf8", errors="replace")
        if t.startswith("---"): t = t[t.find("\n---", 3) + 4:]
        parts = re.split(r"^## \[p\.\d+\]\s*$", t, flags=re.M)
        yield from (parts[1:] if len(parts) > 1 else parts)

def is_abbr(n): return len(n) <= 6 and re.fullmatch(r"[A-Z0-9][A-Z0-9%/+-]*", n) is not None

def names_of(term):
    out = [term["term"]] + list(term.get("abbr") or []) + list(term.get("also") or [])
    seen, res = set(), []
    for n in out:
        if n.lower() not in seen: seen.add(n.lower()); res.append(n)
    return res

def build(terms):
    ci, cs, owner = [], [], collections.defaultdict(set)
    for t in terms:
        for n in names_of(t):
            (cs if is_abbr(n) else ci).append(n); owner[n.lower() if not is_abbr(n) else n].add(t["id"])
    def rx(lst, flags):
        lst = sorted(set(lst), key=len, reverse=True)
        return re.compile(r"(?<![A-Za-z0-9])(" + "|".join(re.escape(x).replace(r"\ ", r"[\s\-]") for x in lst) + r")(?![A-Za-z0-9])", flags)
    return rx(ci, re.I), rx(cs, 0), owner

def norm(s): return re.sub(r"[\s\-]+", " ", s)

def count(folder, terms):
    rci, rcs, owner = build(terms)
    canon = {norm(k): k for k in owner}
    hits, n_units = collections.Counter(), 0
    for u in units(folder):
        n_units += 1; found = set()
        for m in rci.finditer(u): found.add(norm(m.group(1)).lower())
        for m in rcs.finditer(u): found.add(norm(m.group(1)))
        hits.update(found)
    per = collections.defaultdict(dict)
    for k, c in hits.items():
        key = canon.get(k) or canon.get(k.lower())
        for tid in owner.get(key, ()):
            per[tid][key] = c
    return per, n_units

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--collateral", default=str(ROOT / "collateral" / "vendor"))
    ap.add_argument("--write", action="store_true"); ap.add_argument("--min-docs", type=int, default=2)
    ap.add_argument("--only", default="")
    a = ap.parse_args()
    terms = miniyaml.load((ROOT / "principles" / "glossary" / "terms.yaml").read_text(encoding="utf8"))["terms"]
    display = {}
    for t in terms:
        for n in names_of(t): display.setdefault(n.lower() if not is_abbr(n) else n, n)
    for vendor, pf in PLATFORMS.items():
        if a.only and vendor != a.only: continue
        folder = Path(a.collateral) / vendor
        if not folder.exists(): print(f"skip {vendor}: no collateral"); continue
        per, n_units = count(folder, terms)
        rows, missing = [], []
        for t in terms:
            got = sorted(((display[k], c) for k, c in per.get(t["id"], {}).items() if c >= a.min_docs), key=lambda x: -x[1])
            if not got: missing.append(t["id"]); continue
            rows.append({"id": t["id"], "top": got[0][0], "names": [n for n, _ in got],
                         "docs": [c for _, c in got]})
        print(f"{vendor:10s} -> platforms/{pf}: {n_units} units, {len(rows)} terms used, {len(missing)} absent")
        if not a.write: continue
        dest = ROOT / "platforms" / pf / "terms.yaml"; dest.parent.mkdir(parents=True, exist_ok=True)
        keep = ""
        if dest.exists():
            old = dest.read_text(encoding="utf8"); i = old.find("\noverrides:")
            if i >= 0: keep = old[i + 1:]
        head = (f"# GENERATED by tools/glossary/platform_terms.py from collateral/vendor/{vendor} on {time.strftime('%Y-%m-%d')}.\n"
                f"# Which names of each canonical term (principles/glossary/terms.yaml) this platform's own docs use,\n"
                f"# and in how many of its {n_units} doc units (topics or PDF pages). Evidence of usage, not the exact\n"
                f"# on-screen label: confirm in the docs and record the confirmed label under overrides (kept on regeneration).\n"
                f"platform: {pf}\nsource: vendor-{vendor}\ndoc_units: {n_units}\nmin_docs: {a.min_docs}\n"
                f"absent: [{', '.join(missing)}]\nterms:\n")
        body = "\n".join(miniyaml.dump_item(r) for r in rows) + "\n"
        tail = keep if keep else ("overrides:\n# - id: fuel_table\n#   label: 'exact on-screen name'\n"
                                  "#   note: 'where it is in the software; version'\n")
        dest.write_text(head + body + tail, encoding="utf8")
        miniyaml.load(dest.read_text(encoding="utf8"))  # round-trip check

if __name__ == "__main__":
    main()
